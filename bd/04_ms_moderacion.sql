-- =====================================================================
-- Agora Foros - Script 04: tablas y datos del microservicio ms-moderacion
-- Esquema: MODERACION_MS
-- CONTENIDO_ID es el id del tema o comentario en ms-foro (FORO_MS) y
-- USUARIO_ID / MODERADOR_ID el id del usuario en ms-usuarios. No hay llaves
-- foraneas entre esquemas: cada microservicio es dueño de sus datos.
-- =====================================================================
SET DEFINE OFF

CREATE TABLE MODERACION_MS.NORMAS (
  ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODIGO          VARCHAR2(10 CHAR)  NOT NULL,
  TITULO          VARCHAR2(80 CHAR)  NOT NULL,
  DESCRIPCION     VARCHAR2(500 CHAR) NOT NULL,
  GRAVEDAD        VARCHAR2(10 CHAR)  NOT NULL,
  ACTIVA          NUMBER(1)     DEFAULT 1 NOT NULL,
  FECHA_CREACION  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_NORMAS PRIMARY KEY (ID),
  CONSTRAINT UQ_NORMAS_CODIGO UNIQUE (CODIGO),
  CONSTRAINT CK_NORMAS_GRAVEDAD CHECK (GRAVEDAD IN ('BAJA', 'MEDIA', 'ALTA')),
  CONSTRAINT CK_NORMAS_ACTIVA CHECK (ACTIVA IN (0, 1))
);

CREATE TABLE MODERACION_MS.REPORTES (
  ID                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TIPO_CONTENIDO    VARCHAR2(12 CHAR)  NOT NULL,
  CONTENIDO_ID      NUMBER        NOT NULL,
  NORMA_ID          NUMBER        NOT NULL,
  MOTIVO            VARCHAR2(300 CHAR) NOT NULL,
  USUARIO_ID        NUMBER        NOT NULL,
  REPORTADO_POR     VARCHAR2(30 CHAR)  NOT NULL,
  ESTADO            VARCHAR2(12 CHAR)  DEFAULT 'PENDIENTE' NOT NULL,
  RESUELTO_POR      VARCHAR2(30 CHAR),
  OBSERVACION       VARCHAR2(300 CHAR),
  FECHA_CREACION    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_RESOLUCION  TIMESTAMP,
  CONSTRAINT PK_REPORTES PRIMARY KEY (ID),
  CONSTRAINT FK_REPORTES_NORMA FOREIGN KEY (NORMA_ID) REFERENCES MODERACION_MS.NORMAS (ID),
  CONSTRAINT CK_REPORTES_TIPO CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
  CONSTRAINT CK_REPORTES_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'RESUELTO', 'DESCARTADO'))
);

CREATE TABLE MODERACION_MS.SANCIONES (
  ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TIPO_CONTENIDO  VARCHAR2(12 CHAR)  NOT NULL,
  CONTENIDO_ID    NUMBER        NOT NULL,
  ACCION          VARCHAR2(10 CHAR)  NOT NULL,
  NORMA_ID        NUMBER,
  MOTIVO          VARCHAR2(300 CHAR) NOT NULL,
  MODERADOR_ID    NUMBER        NOT NULL,
  MODERADOR       VARCHAR2(30 CHAR)  NOT NULL,
  REPORTE_ID      NUMBER,
  FECHA           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SANCIONES PRIMARY KEY (ID),
  CONSTRAINT FK_SANCIONES_NORMA FOREIGN KEY (NORMA_ID) REFERENCES MODERACION_MS.NORMAS (ID),
  CONSTRAINT FK_SANCIONES_REPORTE FOREIGN KEY (REPORTE_ID) REFERENCES MODERACION_MS.REPORTES (ID),
  CONSTRAINT CK_SANCIONES_TIPO CHECK (TIPO_CONTENIDO IN ('TEMA', 'COMENTARIO')),
  CONSTRAINT CK_SANCIONES_ACCION CHECK (ACCION IN ('BANEAR', 'RESTAURAR')),
  CONSTRAINT CK_SANCIONES_NORMA CHECK (ACCION = 'RESTAURAR' OR NORMA_ID IS NOT NULL)
);

CREATE INDEX MODERACION_MS.IX_REPORTES_CONTENIDO ON MODERACION_MS.REPORTES (TIPO_CONTENIDO, CONTENIDO_ID);
CREATE INDEX MODERACION_MS.IX_REPORTES_ESTADO ON MODERACION_MS.REPORTES (ESTADO);
CREATE INDEX MODERACION_MS.IX_SANCIONES_CONTENIDO ON MODERACION_MS.SANCIONES (TIPO_CONTENIDO, CONTENIDO_ID);

