SET DEFINE OFF

CREATE TABLE USUARIOS_MS.ROLES (
  ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE       VARCHAR2(30)  NOT NULL,
  DESCRIPCION  VARCHAR2(200),
  CONSTRAINT PK_ROLES PRIMARY KEY (ID),
  CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIOS_MS.USUARIOS (
  ID               NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE_USUARIO   VARCHAR2(30)  NOT NULL,
  CORREO           VARCHAR2(120) NOT NULL,
  PASSWORD_HASH    VARCHAR2(100) NOT NULL,
  NOMBRE_COMPLETO  VARCHAR2(100) NOT NULL,
  ROL_ID           NUMBER        NOT NULL,
  ACTIVO           NUMBER(1)     DEFAULT 1 NOT NULL,
  FECHA_REGISTRO   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
  CONSTRAINT UQ_USUARIOS_NOMBRE UNIQUE (NOMBRE_USUARIO),
  CONSTRAINT UQ_USUARIOS_CORREO UNIQUE (CORREO),
  CONSTRAINT FK_USUARIOS_ROL FOREIGN KEY (ROL_ID) REFERENCES USUARIOS_MS.ROLES (ID),
  CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX USUARIOS_MS.IX_USUARIOS_ROL ON USUARIOS_MS.USUARIOS (ROL_ID);

